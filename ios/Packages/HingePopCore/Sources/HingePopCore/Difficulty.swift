extension Campaign {
  /// A campaign level at a difficulty. Normal is `level(_:)` unchanged.
  public static func level(_ n: Int, difficulty: Difficulty) -> LevelSpec {
    difficulty == .normal ? level(n) : Overdrive.spec(level(n))
  }
}
