/// How hard the campaign plays. Normal is the full game as tuned (the hard curve); Overdrive is the same
/// 800 levels run hotter, calibrated so a 2 taps/s player wins about 70% less often on every level.
/// Arcade, Daily, Versus and the tour are the same in both.
public enum Difficulty: String, CaseIterable, Codable, Sendable {
  case normal, overdrive

  public var title: String { self == .normal ? "Normal" : "Overdrive" }
  /// One short line for the switch.
  public var blurb: String { self == .normal ? "The full game." : "70% fewer wins. For experts." }
}

/// Overdrive, in one place: a deterministic transform of a level's spec and tuning.
///
/// Every Overdrive level gets the same flavour (a bigger surge, extra crowns late in a world, a shorter combo
/// window, earlier and steeper overtime, tougher bosses), then its pace is turned up by the level's own `heat`.
/// Heat is calibrated per level with `hp-balance --calibrate` so the 2 taps/s human (`h2`) wins about 0.30× as
/// often as on Normal. See AGENTS.md (Difficulty).
public enum Overdrive {
  /// The target: Overdrive's h2 win rate over Normal's.
  public static let targetRatio = 0.30

  /// The extra pace for level `n`: speed is multiplied by `1 + heat`. Levels past the calibrated table use
  /// the last world's average.
  public static func heat(_ n: Int) -> Double {
    let n = max(1, n)
    let table = calibration
    guard !table.isEmpty else { return defaultHeat }
    if n <= table.count { return max(minHeat, Double(table[n - 1]) / heatScale) }
    let tail = table.suffix(10)
    return max(minHeat, Double(tail.reduce(0) { $0 + Int($1) }) / Double(tail.count) / heatScale)
  }
  /// Heat is stored in hundredths.
  public static let heatScale = 100.0
  public static let minHeat = 0.02
  static let defaultHeat = 0.25

  /// Overdrive's take on a Normal level spec.
  public static func spec(_ normal: LevelSpec, heat: Double? = nil) -> LevelSpec {
    var s = normal
    // The tutorial's lone big bubble can't be rushed into a threat, so Overdrive skips it: levels 1–2 play
    // level 3's crowd, pace and surge.
    if normal.number <= 2, normal.chapter == 1 {
      s = Campaign.level(3)
      s.number = normal.number
    }
    let h = max(minHeat, heat ?? self.heat(normal.number))
    s.speed *= 1 + h
    if !s.isBoss {
      // A bigger last push, and one more crown where the world already crowns.
      s.surge += 1
      let crowned = s.spawns.filter(\.champion).count
      if crowned > 0 { Campaign.crown(&s.spawns, count: 1) }
    }
    return s
  }

  /// Overdrive's take on the tuning: everything that makes play feel hotter without changing what a tap does.
  public static func tuning(_ base: Tuning) -> Tuning {
